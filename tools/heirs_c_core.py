def finalize():
    """Adds the study recipe with every culture item as an ingredient (runs after all content is loaded)."""
    items = []
    for rel, defs in FILES.items():
        for d in defs:
            if d.cls != "ThingDef" or not d.name or rel.startswith("Things/HE_Buildings") or rel.startswith("Core/"):
                continue
            exts = d.fields.get("modExtensions") or []
            if any(isinstance(e, dict) and e.get("@Class") == "HeirsOfEarth.HeirsCultureExt" for e in exts):
                items.append(d.name)
    add(F, Def("RecipeDef", "HE_StudyCulture", label=T("study culture item", "kültür eşyası incele"),
               description=T("Take apart an item from one of the heir nations to learn from it. The item is destroyed; the colony gains Culture Knowledge of its nation.",
                             "Mirasçı devletlerden birine ait bir eşyayı söküp ondan öğren. Eşya yok olur; koloni o devletin Kültür Bilgisini kazanır."),
               jobString=T("Studying a culture item.", "Kültür eşyası inceleniyor."),
               workerClass="HeirsOfEarth.RecipeWorker_HeirsStudy",
               workAmount=1500, workSpeedStat="ResearchSpeed", workSkill="Intellectual", workSkillLearnFactor=0.4,
               soundWorking="Interact_Research",
               ingredients=[{"filter": {"thingDefs": items}, "count": 1}],
               fixedIngredientFilter={"thingDefs": items},
               defaultIngredientFilter={"thingDefs": items}))
    return len(items)
